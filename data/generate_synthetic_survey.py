#!/usr/bin/env python3
"""
Generate a clearly labeled synthetic questionnaire dataset for reproducible
survey data analysis tutorials.

NOTE: All records generated by this script are 100% synthetic (respondent IDs
are prefixed with 'SYN_'). Do NOT treat these numbers as real empirical findings.

Output:
    data/survey_synthetic.csv (300 rows, standard CSV without leading comments)
"""

from __future__ import annotations

import csv
from pathlib import Path
import numpy as np


SEED = 2026
N_RAW = 300

# Target anomaly counts injected into disjoint rows for cleaning demonstration
N_SPEEDERS = 10        # Completion time < 60 seconds
N_STRAIGHTLINERS = 8   # Identical response across all 12 raw Likert items
N_MISSING_ROWS = 6     # Rows containing 1-2 missing values (empty cells)


def generate_likert_items(
    rng: np.random.Generator,
    latent: np.ndarray,
    item_means: list[float],
    loadings: list[float],
    error_sd: float = 0.56,
) -> np.ndarray:
    """
    Generate 4 five-point Likert items (1..5) from a standardized latent factor.
    The 4th item is transformed into a reverse-worded raw response (6 - score).
    """
    n = latent.shape[0]
    items = np.empty((n, 4), dtype=int)
    for j in range(4):
        continuous = item_means[j] + loadings[j] * latent + rng.normal(0.0, error_sd, size=n)
        scored = np.clip(np.rint(continuous), 1, 5).astype(int)
        if j == 3:
            # Store raw response for the reverse-worded item (1 <-> 5, 2 <-> 4, 3 <-> 3)
            scored = 6 - scored
        items[:, j] = scored
    return items


def main() -> None:
    rng = np.random.default_rng(SEED)

    repo_root = Path(__file__).resolve().parent.parent
    output_path = repo_root / "data" / "survey_synthetic.csv"
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # -------------------------------------------------------------------------
    # 1. Generate demographic variables
    # -------------------------------------------------------------------------
    genders = rng.choice(
        ["Female", "Male"],
        size=N_RAW,
        p=[0.54, 0.46],
    )

    grade_levels = ["Freshman", "Sophomore", "Junior", "Senior", "Graduate"]
    grade_idx = rng.choice(
        np.arange(len(grade_levels)),
        size=N_RAW,
        p=[0.18, 0.24, 0.24, 0.19, 0.15],
    )
    grades = np.array([grade_levels[i] for i in grade_idx])

    majors = rng.choice(
        ["STEM", "Humanities & Social Sciences", "Business & Economics"],
        size=N_RAW,
        p=[0.44, 0.30, 0.26],
    )

    # Normal completion time in seconds (log-normal, clipped to [75, 540])
    durations = np.clip(
        np.rint(rng.lognormal(mean=5.28, sigma=0.32, size=N_RAW)),
        75,
        540,
    ).astype(int)

    # -------------------------------------------------------------------------
    # 2. Generate correlated latent constructs:
    #    PU (Perceived Usefulness), SE (Academic Self-Efficacy) -> LE (Learning Engagement)
    # -------------------------------------------------------------------------
    eps1 = rng.normal(0.0, 1.0, size=N_RAW)
    eps2 = rng.normal(0.0, 1.0, size=N_RAW)
    eps3 = rng.normal(0.0, 1.0, size=N_RAW)

    rho_pu_se = 0.44
    z_pu = eps1
    z_se = rho_pu_se * eps1 + np.sqrt(1.0 - rho_pu_se ** 2) * eps2

    # Standardized grade index gives a mild control covariate signal
    grade_std = (grade_idx - np.mean(grade_idx)) / np.std(grade_idx)
    z_le = 0.38 * z_pu + 0.47 * z_se + 0.08 * grade_std + 0.67 * eps3

    # -------------------------------------------------------------------------
    # 3. Discretize latent constructs into 5-point Likert items (4 per construct)
    # -------------------------------------------------------------------------
    pu_items = generate_likert_items(
        rng,
        z_pu,
        item_means=[3.72, 3.64, 3.78, 3.60],
        loadings=[0.74, 0.78, 0.71, 0.75],
        error_sd=0.55,
    )
    se_items = generate_likert_items(
        rng,
        z_se,
        item_means=[3.48, 3.55, 3.38, 3.46],
        loadings=[0.76, 0.79, 0.73, 0.74],
        error_sd=0.55,
    )
    le_items = generate_likert_items(
        rng,
        z_le,
        item_means=[3.58, 3.62, 3.46, 3.54],
        loadings=[0.77, 0.75, 0.79, 0.73],
        error_sd=0.54,
    )

    likert_matrix = np.hstack([pu_items, se_items, le_items])

    # Guard against accidental straight-lining (all 12 raw items equal, e.g. all 3s)
    # in normal rows so cleaning counts reflect strictly the injected straight-liners.
    for row_i in range(N_RAW):
        if np.all(likert_matrix[row_i] == likert_matrix[row_i, 0]):
            likert_matrix[row_i, 0] = 4 if likert_matrix[row_i, 0] == 3 else 3

    # -------------------------------------------------------------------------
    # 4. Inject realistic survey quality anomalies on disjoint rows
    # -------------------------------------------------------------------------
    anomaly_indices = rng.choice(
        N_RAW,
        size=N_SPEEDERS + N_STRAIGHTLINERS + N_MISSING_ROWS,
        replace=False,
    )
    speeder_idx = anomaly_indices[:N_SPEEDERS]
    straight_idx = anomaly_indices[N_SPEEDERS : N_SPEEDERS + N_STRAIGHTLINERS]
    missing_idx = anomaly_indices[N_SPEEDERS + N_STRAIGHTLINERS :]

    # (a) Too-short completion time (< 60s), with noisy random clicks
    durations[speeder_idx] = rng.integers(18, 56, size=N_SPEEDERS)
    likert_matrix[speeder_idx] = rng.integers(1, 6, size=(N_SPEEDERS, 12))

    # (b) Straight-lining: identical answer across all 12 raw items (ignoring reverse items)
    straight_values = rng.choice([2, 3, 4, 5], size=N_STRAIGHTLINERS, p=[0.15, 0.35, 0.35, 0.15])
    for idx, val in zip(straight_idx, straight_values):
        likert_matrix[idx, :] = int(val)

    # Convert table to string cells so we can inject empty strings ("") for missing values
    likert_cols = [
        "PU1", "PU2", "PU3", "PU4_R",
        "SE1", "SE2", "SE3", "SE4_R",
        "LE1", "LE2", "LE3", "LE4_R",
    ]
    header = [
        "respondent_id",
        "gender",
        "grade",
        "major_category",
        "duration_sec",
        *likert_cols,
    ]

    rows: list[list[str]] = []
    for i in range(N_RAW):
        row = [
            f"SYN_{i + 1:03d}",
            str(genders[i]),
            str(grades[i]),
            str(majors[i]),
            str(int(durations[i])),
            *[str(int(v)) for v in likert_matrix[i]],
        ]
        rows.append(row)

    # (c) Missing values: inject 1-2 blank cells per selected row
    # Column indices: 1=gender, 2=grade, 3=major_category, 5..16=Likert items
    for k, idx in enumerate(missing_idx):
        if k == 0:
            # Missing gender + one Likert item
            rows[idx][1] = ""
            rows[idx][7] = ""
        elif k == 1:
            # Missing major_category
            rows[idx][3] = ""
        else:
            # Missing 1 or 2 Likert items
            miss_cols = rng.choice(np.arange(5, 17), size=2 if k % 2 == 0 else 1, replace=False)
            for c in miss_cols:
                rows[idx][int(c)] = ""

    # -------------------------------------------------------------------------
    # 5. Write standard CSV (header on line 1, no comment lines before header)
    # -------------------------------------------------------------------------
    with output_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerow(header)
        writer.writerows(rows)

    print("=== Synthetic Survey Generation Summary ===")
    print(f"Output file           : {output_path.relative_to(repo_root)}")
    print(f"Random seed           : {SEED}")
    print(f"Total synthetic rows  : {N_RAW} (IDs: SYN_001 .. SYN_{N_RAW:03d})")
    print(f"Injected speeders     : {N_SPEEDERS} rows (duration_sec < 60)")
    print(f"Injected straightline : {N_STRAIGHTLINERS} rows (identical across 12 raw Likert items)")
    print(f"Injected missing rows : {N_MISSING_ROWS} rows (1-2 blank cells)")
    print(f"Expected clean sample : {N_RAW - N_SPEEDERS - N_STRAIGHTLINERS - N_MISSING_ROWS} valid rows")


if __name__ == "__main__":
    main()
